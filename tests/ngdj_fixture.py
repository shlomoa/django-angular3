"""The committed ngdj fixture: the command mapping of the adjacent checkout.

``tests/fixtures/ngdj`` is generated by ``sync_command_mapping.py`` from the local
``angular-django2`` checkout (``tests.ngdj_source``), never edited by hand. Tests
read the package spec and the declared OpenUI schema version from it instead of
hard-coding a release, so the fixture can follow the checkout.
"""

from __future__ import annotations

import json
from pathlib import Path

FIXTURE_DIR: Path = Path(__file__).resolve().parent / "fixtures" / "ngdj"


def fixture_version() -> str:
    """The ngdj package version the fixture was synced from."""
    document = json.loads((FIXTURE_DIR / "package.json").read_text(encoding="utf-8"))
    return str(document["version"])


def fixture_package_spec() -> str:
    """The pinned ``name@version`` spec of the fixture package."""
    document = json.loads((FIXTURE_DIR / "package.json").read_text(encoding="utf-8"))
    return f"{document['name']}@{document['version']}"


def fixture_openui_spec_version() -> str:
    """The OpenUI schema version the fixture mapping declares."""
    document = json.loads(
        (FIXTURE_DIR / "command-mapping.json").read_text(encoding="utf-8")
    )
    return str(document["openuiSpecVersion"])
